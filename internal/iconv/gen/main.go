// Command gen regenerates the data files of package iconv from an iconv-lite
// 0.6.3 package directory.
//
// It runs dump.js under Node.js to obtain the merged encoding table that
// iconv-lite builds in encodings/index.js, then writes
//
//   - tables_gen.go: every string alias and every single-byte ("_sbcs")
//     character table, plus the sorted list of the remaining (hand-written)
//     codec entries so that the package tests can detect drift;
//   - tables/*.json: verbatim copies of iconv-lite's double-byte tables,
//     embedded by the package.
//
// Usage, from the package directory:
//
//	go run ./gen -iconv-lite /path/to/node_modules/iconv-lite
package main

import (
	"bytes"
	_ "embed"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

//go:embed dump.js
var dumpScript []byte

// entry is one key of the dumped encoding table; exactly one field is set.
type entry struct {
	Alias *string `json:"alias"`
	SBCS  *string `json:"sbcs"`
	Codec bool    `json:"codec"`
}

func main() {
	pkgDir := flag.String("iconv-lite", "", "path to the iconv-lite package directory (required)")
	node := flag.String("node", "node", "Node.js executable used to run dump.js")
	outFile := flag.String("out", "tables_gen.go", "generated Go file")
	tablesDir := flag.String("tables", "tables", "directory receiving the DBCS JSON tables")
	flag.Parse()
	if *pkgDir == "" {
		log.Fatal("gen: -iconv-lite is required (set ICONV_LITE_DIR for go generate)")
	}
	if err := run(*pkgDir, *node, *outFile, *tablesDir); err != nil {
		log.Fatalf("gen: %v", err)
	}
}

func run(pkgDir, node, outFile, tablesDir string) error {
	table, err := dumpTable(pkgDir, node)
	if err != nil {
		return err
	}
	src, err := render(table)
	if err != nil {
		return err
	}
	if err := os.WriteFile(outFile, src, 0o644); err != nil {
		return err
	}
	return copyTables(filepath.Join(pkgDir, "encodings", "tables"), tablesDir)
}

// dumpTable runs dump.js and decodes its output.
func dumpTable(pkgDir, node string) (map[string]entry, error) {
	var stdout, stderr bytes.Buffer
	cmd := exec.Command(node, "-", pkgDir)
	cmd.Stdin = bytes.NewReader(dumpScript)
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("running dump.js: %w: %s", err, stderr.Bytes())
	}
	table := map[string]entry{}
	if err := json.Unmarshal(stdout.Bytes(), &table); err != nil {
		return nil, fmt.Errorf("decoding dump.js output: %w", err)
	}
	return table, nil
}

// render produces the formatted source of tables_gen.go.
func render(table map[string]entry) ([]byte, error) {
	names := make([]string, 0, len(table))
	for name := range table {
		names = append(names, name)
	}
	sort.Strings(names)

	var aliases, sbcs, codecs bytes.Buffer
	for _, name := range names {
		e := table[name]
		switch {
		case e.Alias != nil:
			fmt.Fprintf(&aliases, "\t%s: %s,\n", strconv.Quote(name), strconv.Quote(*e.Alias))
		case e.SBCS != nil:
			fmt.Fprintf(&sbcs, "\t%s: %s,\n", strconv.Quote(name), strconv.Quote(*e.SBCS))
		case e.Codec:
			fmt.Fprintf(&codecs, "\t%s,\n", strconv.Quote(name))
		default:
			return nil, fmt.Errorf("entry %q has no recognised shape", name)
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\n\n")
	b.WriteString("package iconv\n\n")
	b.WriteString("// aliasTable holds every string entry of iconv-lite's merged encoding\n")
	b.WriteString("// table: canonical name -> the name it stands for.\n")
	b.WriteString("var aliasTable = map[string]string{\n" + aliases.String() + "}\n\n")
	b.WriteString("// sbcsTable holds the \"chars\" of every {type: \"_sbcs\"} entry\n")
	b.WriteString("// (sbcs-data.js and sbcs-data-generated.js). A 128-char table covers bytes\n")
	b.WriteString("// 0x80-0xFF only; sbcs-codec.js prepends ASCII to it.\n")
	b.WriteString("var sbcsTable = map[string]string{\n" + sbcs.String() + "}\n\n")
	b.WriteString("// generatedCodecNames lists the remaining entries (codec functions and\n")
	b.WriteString("// option objects), which codecDefs implements by hand.\n")
	b.WriteString("var generatedCodecNames = []string{\n" + codecs.String() + "}\n")
	return format.Source([]byte(b.String()))
}

// copyTables copies the DBCS JSON tables verbatim.
func copyTables(from, to string) error {
	if err := os.MkdirAll(to, 0o755); err != nil {
		return err
	}
	matches, err := filepath.Glob(filepath.Join(from, "*.json"))
	if err != nil {
		return err
	}
	if len(matches) == 0 {
		return fmt.Errorf("no tables found in %s: %w", from, fs.ErrNotExist)
	}
	for _, m := range matches {
		data, err := os.ReadFile(m)
		if err != nil {
			return err
		}
		if !json.Valid(data) {
			return errors.New("invalid JSON table " + m)
		}
		if err := os.WriteFile(filepath.Join(to, filepath.Base(m)), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}
