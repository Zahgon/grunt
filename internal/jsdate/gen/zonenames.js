// zonenames.js writes zonenames_gen.go, the names V8 prints in parentheses at the end
// of Date.prototype.toString for each IANA time zone (ICU's long specific names, such
// as "Eastern Standard Time" and "Eastern Daylight Time").
//
//     node gen/zonenames.js /usr/share/zoneinfo > zonenames_gen.go && gofmt -w zonenames_gen.go
//
// It lists every zone file (links included) under the given zoneinfo directory, sets
// process.env.TZ to each in turn (Node resets V8's time zone cache when TZ changes)
// and records the offset and name String(date) shows in mid-January and mid-July of
// 2026. Of two different offsets, the smaller is the zone's standard time and the
// larger its daylight-saving time; a zone with one offset has the same name twice.
"use strict";
const fs = require("fs");
const path = require("path");

const root = process.argv[2] || "/usr/share/zoneinfo";

function zones(dir, prefix) {
  const out = [];
  for (const name of fs.readdirSync(dir).sort()) {
    if (name === "posix" || name === "right") continue;
    const full = path.join(dir, name);
    const rel = prefix ? prefix + "/" + name : name;
    const st = fs.statSync(full);
    if (st.isDirectory()) {
      out.push(...zones(full, rel));
      continue;
    }
    const magic = Buffer.alloc(4);
    const fd = fs.openSync(full, "r");
    try {
      fs.readSync(fd, magic, 0, 4, 0);
    } finally {
      fs.closeSync(fd);
    }
    if (magic.toString("latin1") === "TZif") out.push(rel);
  }
  return out;
}

const instants = [Date.UTC(2026, 0, 15, 12), Date.UTC(2026, 6, 15, 12)];
const names = [];
const index = new Map();
function nameIndex(n) {
  if (!index.has(n)) {
    index.set(n, names.length);
    names.push(n);
  }
  return index.get(n);
}

const rows = [];
for (const zone of zones(root, "")) {
  process.env.TZ = zone;
  const seen = new Map();
  for (const t of instants) {
    const d = new Date(t);
    const offset = -d.getTimezoneOffset() * 60;
    const name = /\(([^)]*)\)$/.exec(String(d))[1];
    seen.set(offset, name);
  }
  const entries = [...seen].sort((a, b) => a[0] - b[0]);
  const std = entries[0];
  const dst = entries[entries.length - 1];
  rows.push(`\t${JSON.stringify(zone)}: {${nameIndex(std[1])}, ${nameIndex(dst[1])}},`);
}

const out = [];
out.push("// Code generated by gen/zonenames.js from Node " + process.version + " (ICU " + process.versions.icu + "); DO NOT EDIT.");
out.push("");
out.push("package jsdate");
out.push("");
out.push("// zoneNameList holds the distinct names of zoneNames.");
out.push("var zoneNameList = [...]string{");
for (const n of names) out.push("\t" + JSON.stringify(n) + ",");
out.push("}");
out.push("");
out.push("// zoneNames maps an IANA time zone to the indexes in zoneNameList of the names V8");
out.push("// prints for its standard and daylight-saving time.");
out.push("var zoneNames = map[string]zoneNamePair{");
out.push(...rows);
out.push("}");
process.stdout.write(out.join("\n") + "\n");
